        x12 = self.ln_post(x12)  

        if self.proj is not None:
            xproj = x12 @ self.proj
    
        # return x
        ### 再把 0 向量填充回去
        if input_img_type != InputImageType.rgb:
            _fill_x11 = torch.zeros((_mask.shape[0], x11.shape[1], x11.shape[2]), device=x11.device, dtype=x11.dtype)  # bs, 193, 512
