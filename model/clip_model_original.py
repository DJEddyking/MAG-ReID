class QuickGELU(nn.Module):
    def forward(self, x: torch.Tensor):
        return x * torch.sigmoid(1.702 * x)


class Adapter(nn.Module):
    def __init__(self,
                #  config=None,
                 d_model=None,
                 bottleneck=None,
                 dropout=0.0,
                 init_option="bert",
                 adapter_scalar="1.0",
                 adapter_layernorm_option="in"):
        super().__init__()
        self.n_embd = d_model # config.d_model if d_model is None else d_model
        self.down_size = bottleneck # config.attn_bn if bottleneck is None else bottleneck, 下采样的维度

        #_before
        self.adapter_layernorm_option = adapter_layernorm_option

        self.adapter_layer_norm_before = None
        if adapter_layernorm_option == "in" or adapter_layernorm_option == "out":
            # 使用自定义 LayerNorm（内部转 fp32 再回转）以避免 AMP 下 Half/Float 冲突
            self.adapter_layer_norm_before = LayerNorm(self.n_embd)

        if adapter_scalar == "learnable_scalar":
            self.scale = nn.Parameter(torch.ones(1))
        else:
            self.scale = float(adapter_scalar)

        self.down_proj = nn.Linear(self.n_embd, self.down_size)
        self.non_linear_func = QuickGELU() # nn.ReLU()
        self.up_proj = nn.Linear(self.down_size, self.n_embd)

        self.dropout = dropout
        if init_option == "bert":
            raise NotImplementedError
        elif init_option == "lora":  ########## 本质上就是 Lora ???
            with torch.no_grad():
                nn.init.kaiming_uniform_(self.down_proj.weight,  a=0, mode='fan_in', nonlinearity='relu')#, a=math.sqrt(5))  ##### 
                nn.init.zeros_(self.up_proj.weight)
                nn.init.zeros_(self.down_proj.bias)
                nn.init.zeros_(self.up_proj.bias)

    def forward(self, x, add_residual=True, residual=None):
        residual = x if residual is None else residual
        if self.adapter_layernorm_option == 'in':
            x = self.adapter_layer_norm_before(x)

        down = self.down_proj(x)
        down = self.non_linear_func(down)
        down = nn.functional.dropout(down, p=self.dropout, training=self.training)  ###
        up = self.up_proj(down)

        up = up * self.scale

        if self.adapter_layernorm_option == 'out':
            up = self.adapter_layer_norm_before(up)

        if add_residual:
            output = up + residual
        else:
            output = up

        return output


class SharedLoRALinear(nn.Linear):
    """A single shared parallel LoRA branch for a ViT Linear layer."""
    def __init__(self, in_features, out_features, bias=True, rank=4, alpha=4, freeze_base=False):
        super().__init__(in_features, out_features, bias=bias)
        self.rank = rank
        self.alpha = alpha
        self.scaling = self.alpha / self.rank
        self.lora_A = nn.Parameter(torch.empty(rank, in_features))
        self.lora_B = nn.Parameter(torch.zeros(out_features, rank))
        nn.init.kaiming_uniform_(self.lora_A, a=math.sqrt(5))
        nn.init.zeros_(self.lora_B)
        if freeze_base:
            self.weight.requires_grad = False
            if self.bias is not None:
                self.bias.requires_grad = False

    @classmethod
    def from_linear(cls, linear, rank=4, alpha=4, freeze_base=False):
        lora_linear = cls(
            linear.in_features,
            linear.out_features,
            bias=linear.bias is not None,
            rank=rank,
            alpha=alpha,
            freeze_base=freeze_base,
        )
        lora_linear.to(device=linear.weight.device, dtype=linear.weight.dtype)
        with torch.no_grad():
            lora_linear.weight.copy_(linear.weight)
            if linear.bias is not None:
                lora_linear.bias.copy_(linear.bias)
        if not freeze_base:
            lora_linear.weight.requires_grad = linear.weight.requires_grad
            if lora_linear.bias is not None:
                lora_linear.bias.requires_grad = linear.bias.requires_grad
        return lora_linear

    @classmethod
    def inject(cls, module, rank=4, alpha=4, freeze_base=False):
        for name, child in list(module.named_children()):
            if isinstance(child, nn.MultiheadAttention):
                cls.inject_attention(child, rank=rank, alpha=alpha, freeze_base=freeze_base)
            elif isinstance(child, nn.Linear) and not isinstance(child, cls):
                setattr(module, name, cls.from_linear(child, rank=rank, alpha=alpha, freeze_base=freeze_base))
            else:
                cls.inject(child, rank=rank, alpha=alpha, freeze_base=freeze_base)
        return module

    @classmethod
    def inject_attention(cls, attention, rank=4, alpha=4, freeze_base=False):
        if hasattr(attention, "lora_in_A"):
            return attention
        if not attention._qkv_same_embed_dim:
            raise NotImplementedError("SharedLoRALinear only supports packed qkv attention weights.")

        attention.lora_rank = rank
        attention.lora_alpha = alpha
        attention.lora_scaling = alpha / rank
        attention.lora_in_A = nn.Parameter(attention.in_proj_weight.new_empty(rank, attention.embed_dim))
        attention.lora_in_B = nn.Parameter(attention.in_proj_weight.new_zeros(3 * attention.embed_dim, rank))
        attention.lora_out_A = nn.Parameter(attention.out_proj.weight.new_empty(rank, attention.embed_dim))
        attention.lora_out_B = nn.Parameter(attention.out_proj.weight.new_zeros(attention.embed_dim, rank))
        nn.init.kaiming_uniform_(attention.lora_in_A, a=math.sqrt(5))
        nn.init.zeros_(attention.lora_in_B)
        nn.init.kaiming_uniform_(attention.lora_out_A, a=math.sqrt(5))
        nn.init.zeros_(attention.lora_out_B)

        if freeze_base:
            attention.in_proj_weight.requires_grad = False
            if attention.in_proj_bias is not None:
                attention.in_proj_bias.requires_grad = False
            attention.out_proj.weight.requires_grad = False
            if attention.out_proj.bias is not None:
                attention.out_proj.bias.requires_grad = False

        def forward_with_shared_lora(
                self,
                query: Tensor,
                key: Tensor,
                value: Tensor,
                key_padding_mask: Optional[Tensor] = None,
                need_weights: bool = True,
                attn_mask: Optional[Tensor] = None,
                average_attn_weights: bool = True,
                is_causal: bool = False):
            is_batched = query.dim() == 3
            if self.batch_first and is_batched:
                query, key, value = (x.transpose(1, 0) for x in (query, key, value))

            in_delta = torch.matmul(
                self.lora_in_B.to(dtype=query.dtype),
                self.lora_in_A.to(dtype=query.dtype),
            ) * self.lora_scaling
            out_delta = torch.matmul(
                self.lora_out_B.to(dtype=query.dtype),
                self.lora_out_A.to(dtype=query.dtype),
            ) * self.lora_scaling
            in_proj_weight = self.in_proj_weight.to(dtype=query.dtype) + in_delta
            in_proj_bias = self.in_proj_bias.to(dtype=query.dtype) if self.in_proj_bias is not None else None
            out_proj_weight = self.out_proj.weight.to(dtype=query.dtype) + out_delta
            out_proj_bias = self.out_proj.bias.to(dtype=query.dtype) if self.out_proj.bias is not None else None

            attn_output, attn_output_weights = F.multi_head_attention_forward(
                query,
                key,
                value,
                self.embed_dim,
                self.num_heads,
                in_proj_weight,
                in_proj_bias,
                self.bias_k,
                self.bias_v,
                self.add_zero_attn,
                self.dropout,
                out_proj_weight,
                out_proj_bias,
                training=self.training,
                key_padding_mask=key_padding_mask,
                need_weights=need_weights,
                attn_mask=attn_mask,
                average_attn_weights=average_attn_weights,
                is_causal=is_causal,
            )
            if self.batch_first and is_batched:
                attn_output = attn_output.transpose(1, 0)
            return attn_output, attn_output_weights

        attention.forward = forward_with_shared_lora.__get__(attention, attention.__class__)
        return attention

    def forward(self, x):
        weight = self.weight.to(dtype=x.dtype)
        bias = self.bias.to(dtype=x.dtype) if self.bias is not None else None
        base = F.linear(x, weight, bias)
        lora_A = self.lora_A.to(dtype=x.dtype)
        lora_B = self.lora_B.to(dtype=x.dtype)
        delta = F.linear(F.linear(x, lora_A), lora_B)
        return base + delta * self.scaling


class LoRaExpertQKV(nn.Module):
    """
     y = W·x + (alpha/r) * B·A·x
    """
    def __init__(self,
                in_features, 
                out_features,
                 rank=4,
                 alpha=32,
                 weight=None,  ### 全连接层自带的权重和偏置
                 bias=None,
                 dropout=0.0):
        super().__init__()
        self.rank = rank
        self.alpha = alpha
        self.weight = weight
        self.bias = bias

        self.lora_A = nn.Parameter(torch.randn(in_features, rank))
        self.lora_B = nn.Parameter(torch.zeros(rank, out_features))
        
        self.scaling = self.alpha / self.rank
        self.lora_dropout = nn.Dropout(dropout) if dropout > 0 else nn.Identity()

        with torch.no_grad():
            nn.init.kaiming_uniform_(self.lora_A, a=math.sqrt(5))
            nn.init.zeros_(self.lora_B)
        # 冻结底座权重，仅训练 LoRA
        if isinstance(self.weight, torch.nn.Parameter):
            self.weight.requires_grad = False
        if (self.bias is not None) and isinstance(self.bias, torch.nn.Parameter):
            self.bias.requires_grad = False
        # 冻结底座权重，仅训练 LoRA
        if isinstance(self.weight, torch.nn.Parameter):
            self.weight.requires_grad = False
        if (self.bias is not None) and isinstance(self.bias, torch.nn.Parameter):
            self.bias.requires_grad = False

    def forward(self, x):
        # B,N,C比二维高用 einsum or torch manual
        B, N, C = x.shape
        # 计算时将权重/LoRA核对齐到输入 dtype（不改变参数本体 dtype）
        weight = self.weight.to(dtype=x.dtype) if isinstance(self.weight, torch.Tensor) else self.weight
        bias = self.bias.to(dtype=x.dtype) if isinstance(self.bias, torch.Tensor) else self.bias
        lora_A = self.lora_A.to(dtype=x.dtype)
        lora_B = self.lora_B.to(dtype=x.dtype)

        x = x.view(B, N, 3, -1)  # [bs, n, 3, 768]
        o_w = weight.view(3, -1, C // 3)  ## [3, 768, 768]
        # 逐个通道求解: original weights
        q = torch.einsum('bny,xy->bnx', x[:, :, 0,:], o_w[0])   # [B, N, 768]
        k = torch.einsum('bny,xy->bnx', x[:, :, 1,:], o_w[1])
        v = torch.einsum('bny,xy->bnx', x[:, :, 2,:], o_w[2])
        base = torch.concat((q,k,v), dim=2)
        if bias is not None:
            base = base + bias

        # ΔW = lora_B @ lora_A
        lora_A_v = lora_A.view(3, C//3, -1)
        delta_q = torch.einsum('bnx,xr->bnr', self.lora_dropout(x[:, :, 0,:]), lora_A_v[0])   # [B, N, 768]
        delta_q = torch.einsum('bnr,rx->bnx', delta_q, lora_B)
        out_q = q + delta_q * self.scaling

        delta_k = torch.einsum('bnx,xr->bnr', self.lora_dropout(x[:, :, 1,:]), lora_A_v[1])
        delta_k = torch.einsum('bnr,rx->bnx', delta_k, lora_B)
