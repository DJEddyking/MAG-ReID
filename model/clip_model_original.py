def _resolve_adapter_layers(adapter_layers):
    if adapter_layers is None:
        return set(range(0, 6))
    if isinstance(adapter_layers, str):
        adapter_layers = [int(x) for x in adapter_layers.replace(",", " ").split()]
    adapter_layers = list(adapter_layers)
    if len(adapter_layers) == 2:
        return set(range(adapter_layers[0], adapter_layers[1]))
    return set(adapter_layers)


def _resolve_vit_single_lora_layers(layer_spec, num_layers):
    if layer_spec is None:
        return set(range(num_layers))
    if isinstance(layer_spec, str):
        layer_spec = [int(x) for x in layer_spec.replace(",", " ").split()]
    elif isinstance(layer_spec, int):
        layer_spec = [layer_spec]
    else:
        layer_spec = list(layer_spec)

    if len(layer_spec) == 0:
        return set()
    if len(layer_spec) == 1:
        start, end = 0, layer_spec[0]
        return set(range(max(0, start), min(end, num_layers)))
    if len(layer_spec) == 2:
        start, end = layer_spec
        return set(range(max(0, start), min(end, num_layers)))
    return {idx for idx in layer_spec if 0 <= idx < num_layers}


