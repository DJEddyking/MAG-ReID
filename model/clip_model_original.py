def _topk_gate_probs(gate, x, top_k):
    gate_weight = gate.weight.to(dtype=x.dtype)
    gate_bias = gate.bias.to(dtype=x.dtype) if gate.bias is not None else None
    gate_logits = F.linear(x, gate_weight, gate_bias)
    gate_probs = F.softmax(gate_logits.float(), dim=-1)
    topk_probs, topk_indices = torch.topk(gate_probs, k=top_k, dim=-1)
    topk_probs = topk_probs / topk_probs.sum(dim=-1, keepdim=True).clamp_min(1e-12)
    return topk_probs.to(dtype=x.dtype), topk_indices


